test_that("cached records are reused and only missing IDs are fetched", {
    localCache()
    fake <- fakeBacDive(c(5, 150, 250))
    local_mocked_bindings(.bdFetchBatch = fake$fetch)
    expect_message(first <- bdFetch(c(5, 6, 150)), "1 BacDive ID")
    expect_identical(names(first), c("5", "150"))
    expect_identical(fake$requests, list(c(5L, 6L, 150L)))
    ## 5, 6 and 150 are known (6 does not exist); only 250 is requested.
    expect_message(second <- bdFetch(c(250, 6, 5, 150)), "1 BacDive ID")
    expect_identical(names(second), c("250", "5", "150"))
    expect_identical(fake$requests[[2L]], 250L)
    expect_length(fake$requests, 2L)
    expect_identical(second[["5"]], first[["5"]])
})

test_that("records with predictions are cached separately", {
    localCache()
    fake <- fakeBacDive(1:10)
    local_mocked_bindings(.bdFetchBatch = fake$fetch)
    bdFetch(1:3)
    bdFetch(1:3, predictions = TRUE)
    bdFetch(1:3, predictions = TRUE)
    expect_length(fake$requests, 2L)
    expect_identical(bdCachedIds(), 1:3)
    expect_identical(bdCachedIds(predictions = TRUE), 1:3)
})

test_that("cache = FALSE bypasses the cache", {
    localCache()
    fake <- fakeBacDive(1:10)
    local_mocked_bindings(.bdFetchBatch = fake$fetch)
    bdFetch(1:3, cache = FALSE)
    bdFetch(1:3, cache = FALSE)
    expect_length(fake$requests, 2L)
    expect_identical(bdCachedIds(), integer())
})

test_that("bdCacheInfo reports and bdCacheClear deletes the cache", {
    localCache()
    info <- bdCacheInfo()
    expect_identical(info$strains, 0L)
    expect_identical(info$size, 0)
    local_mocked_bindings(.bdFetchBatch = fakeBacDive(1:500)$fetch)
    bdFetch(c(1:3, 450))
    info <- bdCacheInfo()
    expect_identical(info$strains, 4L)
    expect_identical(info$strainsWithPredictions, 0L)
    expect_identical(info$releases, "20260601.11")
    expect_true(info$size > 0)
    expect_s3_class(info$updated, "POSIXct")
    expect_true(info$enabled)
    expect_message(bdCacheClear(ask = FALSE), "Deleted")
    expect_false(dir.exists(info$path))
    expect_message(bdCacheClear(ask = FALSE), "empty")
    expect_identical(bdCacheInfo()$strains, 0L)
})

test_that("the cache choice is remembered", {
    withr::local_options(bdiver.cache = NULL,
        bdiver.config_dir = withr::local_tempdir())
    expect_null(.bdCacheChoice())
    expect_false(.bdUseCache())   # not interactive: no cache, no question
    expect_null(.bdCacheChoice())
    expect_null(.bdStartupMessage(interactive = FALSE))
    expect_match(.bdStartupMessage(interactive = TRUE), "bdCacheEnable()",
        fixed = TRUE)
    expect_message(bdCacheEnable(), "Caching")
    expect_true(.bdUseCache())
    expect_message(bdCacheDisable(), "bdCacheClear")
    expect_false(.bdUseCache())
    withr::local_options(bdiver.cache = TRUE)
    expect_true(.bdUseCache())
})

test_that("the startup message reports the cache", {
    localCache()
    local_mocked_bindings(.bdFetchBatch = fakeBacDive(1)$fetch)
    expect_null(.bdStartupMessage())
    bdFetch(1)
    expect_match(.bdStartupMessage(), "bdiver cache: ")
    withr::local_options(bdiver.cache = FALSE)
    expect_match(.bdStartupMessage(), "Caching is turned off")
})

test_that("bdCacheInfo prints a description of the cache", {
    localCache()
    expect_output(print(bdCacheInfo()), "The cache is empty")
    local_mocked_bindings(.bdFetchBatch = fakeBacDive(1:5)$fetch)
    bdFetch(1:5)
    expect_output(print(bdCacheInfo()), "5 strains .* from BacDive release")
    expect_output(print(bdCacheInfo()), "bdCacheClear()", fixed = TRUE)
})
